-- ============================================================================
-- PART 1 — Remove the single-profile lock and make profile.id auto-generate.
--   Without this a second tenant's profile row cannot exist (Create Tenant fails).
-- ============================================================================
ALTER TABLE profile DROP CONSTRAINT IF EXISTS single_profile;
ALTER TABLE profile ALTER COLUMN id DROP DEFAULT;
-- Keep the existing id = 1 row; new rows auto-assign id = 2, 3, ... so the app can
-- INSERT a profile without supplying an id.
ALTER TABLE profile ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 2);
-- One profile per tenant (the new effective key).
ALTER TABLE profile ADD CONSTRAINT uq_profile_tenant UNIQUE (tenant_id);


-- ============================================================================
-- PART 2 — Enforce tenant ownership (rejects null tenant_id going forward).
--   Only run once you've confirmed NO row has a null tenant_id (Section B backfill).
