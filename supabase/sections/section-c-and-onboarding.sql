-- 3a. Per-tenant data isolation (replaces the un-scoped is_admin() writes).
CREATE POLICY "Tenant admins write profile"  ON profile          FOR ALL    TO authenticated USING (is_tenant_admin(tenant_id)) WITH CHECK (is_tenant_admin(tenant_id));
CREATE POLICY "Tenant admins write projects" ON projects         FOR ALL    TO authenticated USING (is_tenant_admin(tenant_id)) WITH CHECK (is_tenant_admin(tenant_id));
CREATE POLICY "Tenant admins read events"    ON analytics_events FOR SELECT TO authenticated USING (is_tenant_admin(tenant_id));

-- 3b. Onboarding: allow an authenticated admin to create a tenant, and to own the
--     row they just created. (tenants currently has only a public-read policy.)
--     "create then self-own" — a tenant is creatable by any signed-in admin; its
--     domains/data are then gated by is_tenant_admin() above.
GRANT INSERT, UPDATE ON tenants        TO authenticated;
GRANT INSERT, UPDATE, DELETE ON tenant_admins  TO authenticated;
GRANT SELECT ON tenant_admins TO authenticated;
GRANT INSERT, UPDATE, DELETE ON tenant_domains TO authenticated;

DROP POLICY IF EXISTS "Admins create tenants" ON tenants;
CREATE POLICY "Admins create tenants" ON tenants
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM admin_usernames WHERE user_id = auth.uid()));
DROP POLICY IF EXISTS "Tenant admins update tenant" ON tenants;
CREATE POLICY "Tenant admins update tenant" ON tenants
  FOR UPDATE TO authenticated USING (is_tenant_admin(id)) WITH CHECK (is_tenant_admin(id));

-- 3c. tenant_admins: an admin may read their own mappings and create the owner row
--     for a tenant they just created (self-assignment only).
ALTER TABLE tenant_admins ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins read own tenant mappings" ON tenant_admins;
CREATE POLICY "Admins read own tenant mappings" ON tenant_admins
  FOR SELECT TO authenticated USING (user_id = auth.uid());
DROP POLICY IF EXISTS "Admins self-assign new tenant" ON tenant_admins;
CREATE POLICY "Admins self-assign new tenant" ON tenant_admins
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

-- 3d. tenant_domains: only a tenant's admins may add/remove its domains. Public read
--     already exists from Section A (needed by the resolver).
DROP POLICY IF EXISTS "Tenant admins manage domains" ON tenant_domains;
CREATE POLICY "Tenant admins manage domains" ON tenant_domains
  FOR ALL TO authenticated USING (is_tenant_admin(tenant_id)) WITH CHECK (is_tenant_admin(tenant_id));

-- 3e. Assign a CLIENT as admin of a tenant you already administer (the "assign a
--     client admin" onboarding step; called by the admin UI via supabase.rpc()).
--     SECURITY DEFINER so it can resolve username -> user_id and insert the mapping
--     WITHOUT exposing admin_usernames or other users' mappings to the browser
--     (tenant_admins stays readable only for your own rows, per 3c).
CREATE OR REPLACE FUNCTION assign_tenant_admin(p_tenant_id UUID, p_username TEXT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user UUID;
BEGIN
  -- the caller must already administer this tenant
  IF NOT is_tenant_admin(p_tenant_id) THEN
    RAISE EXCEPTION 'not an admin of this tenant';
  END IF;
  SELECT user_id INTO v_user FROM admin_usernames WHERE username = p_username;
  IF v_user IS NULL THEN
    RAISE EXCEPTION 'no user with that username';
  END IF;
  INSERT INTO tenant_admins (tenant_id, user_id, role)
  VALUES (p_tenant_id, v_user, 'owner')
  ON CONFLICT (tenant_id, user_id) DO NOTHING;
END;
$$;
GRANT EXECUTE ON FUNCTION assign_tenant_admin(UUID, TEXT) TO authenticated;

