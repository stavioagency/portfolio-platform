export const BRAND_KEYS = Object.keys(BRAND_ICONS);

// Legacy backwards-compat: migration v3 accidentally stored emoji strings
// as icon values instead of brand keys. Normalize on read so old data
// still renders correctly until migration v5 cleans it up.
const EMOJI_TO_BRAND = {
  '📷': 'instagram',
  '𝕏': 'x',
  '💼': 'linkedin',
  '🎨': 'behance',
  '💬': 'whatsapp',
  '✉️': 'email',
  '🌐': 'website',
  '🔗': 'website',
};

export function normalizeIcon(icon) {
  if (!icon) return null;
  return EMOJI_TO_BRAND[icon] || icon;
}

export function brandIcon(key) {
  const k = normalizeIcon(key);
  return BRAND_ICONS[k] || null;
}

// The colour to paint this brand's glyph on the given surface.
//
// Returns null when the brand has no colour of its own (email, website) or is
// unknown — callers MUST treat null as "inherit currentColor" and keep their
// existing neutral styling, so an unrecognised icon never renders invisible.
//
// `surface` is 'dark' (the default, matching the public portfolio card and the
// admin's default theme) or 'light'.
export function brandColor(key, surface = 'dark') {
  const ic = brandIcon(key);
  if (!ic) return null;
  if (surface === 'dark' && ic.colorOnDark) return ic.colorOnDark;
  if (surface === 'light' && ic.colorOnLight) return ic.colorOnLight;
  return ic.color || null;
}
