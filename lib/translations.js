export function getTranslator(lang) {
  return (key) => translations[lang]?.[key] || translations.en[key] || key;
}

// The languages this product actually has. Anything else is not a language
// we can render, and must never reach getTranslator(): that function falls
// back to English for an unknown key, so an unrecognised value produces an
// English page that labels itself something else.
export const LANGS = ['ar', 'en'];

export function isLang(value) {
  return LANGS.includes(value);
}

/**
 * Decide which language to render, given a URL parameter and whatever was
 * stored from a previous visit.
 *
 * The URL wins. A visitor can reach /subscribe from the marketing site,
 * which is a different origin — localStorage is empty there, so without
 * the parameter an English reader lands on an Arabic checkout. The link is
 * the only thing that knows what they were reading, so it decides.
 *
 * Both inputs are validated rather than trusted. `stored` gets the same
 * treatment as the URL because callers persist the result, so one bad
 * value written once would otherwise round-trip forever.
 *
 * Arabic is the fallback: this product is Arabic-first.
 */
export function resolveLang(requested, stored) {
  if (isLang(requested)) return requested;
  if (isLang(stored)) return stored;
  return 'ar';
}
